class I18n(QObject):
    languageChanged = Signal()

    def __init__(self) -> None:
        super().__init__()
        self._settings = QSettings("Wemute", "Wemute")
        self._mode = str(self._settings.value("language", "system"))
        self._language = self._resolve(self._mode)

    @staticmethod
    def _resolve(mode: str) -> str:
        if mode in TRANSLATIONS:
            return mode
        return "zh" if QLocale.system().name().lower().startswith("zh") else "en"

    @Property(str, notify=languageChanged)
    def language(self) -> str:
        return self._language

    @Property(str, notify=languageChanged)
    def mode(self) -> str:
        return self._mode if self._mode in TRANSLATIONS else "system"

    @Slot(str)
    def setMode(self, mode: str) -> None:
        mode = mode if mode in TRANSLATIONS else "system"
        self._mode = mode
        self._settings.setValue("language", mode)
        self._language = self._resolve(mode)
        self.languageChanged.emit()

    def override(self, language: str) -> None:
        """Use a language for this session only, without saving it."""
        if language in TRANSLATIONS:
            self._mode = language
            self._language = language
            self.languageChanged.emit()

    @Slot(str, result=str)
    def t(self, key: str) -> str:
        return TRANSLATIONS[self._language].get(key, key)

    @Slot(str, int, result=str)
    def count(self, key: str, value: int) -> str:
        selected = "file" if value == 1 and key == "files" else key
        return TRANSLATIONS[self._language].get(selected, key).format(count=value)
